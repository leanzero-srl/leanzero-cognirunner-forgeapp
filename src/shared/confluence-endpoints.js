/**
 * Confluence Cloud endpoints reachable from Forge via `asApp().requestConfluence()`.
 *
 * SINGLE SOURCE OF TRUTH for the Confluence half of release 1.5 (plan §3.12,
 * FRAME commit 6) — consumed by:
 *   - the Custom UI endpoint picker (the same component that renders jira-endpoints.js)
 *   - the backend AI prompts, via buildConfluenceEndpointPromptBlock
 *   - src/confluence-client.js, which is the ONLY module allowed to call
 *     requestConfluence; a second call site anywhere is a finding.
 *
 * DELIBERATELY THE SAME SHAPE AS src/shared/jira-endpoints.js — every entry has
 * exactly the keys { category, method, path, description, params, body, notes }
 * so the picker and the prompt builder need no product-specific branch. A shape
 * parity test (test-harness/scripts/confluence-endpoints.test.mjs) fails the
 * offline suite if the two catalogues drift apart.
 *
 * EVERY path starts with `/wiki/` — that prefix is what `requestConfluence`
 * expects on a Cloud site, and it is asserted by the parity test rather than
 * left to review.
 *
 * v2 vs v1: the modern REST surface (`/wiki/api/v2/...`) is used for pages,
 * spaces, comments and attachments. CQL search has no v2 equivalent, so search
 * stays on `/wiki/rest/api/search`; that asymmetry is called out in the notes of
 * the Search entries rather than hidden.
 *
 * Keep dependency-free so it bundles into both the Forge backend and the
 * frontends (asserted by scripts/shared-imports.test.mjs).
 *
 * NOT A PERMISSION STATEMENT. Listing an endpoint here does not mean the app
 * currently holds the scope for it: the write/comment scopes
 * (write:page:confluence, read:comment:confluence, write:comment:confluence)
 * are a MAJOR manifest bump cut later with the Confluence actions. Entries that
 * need a scope the manifest does not yet carry say so in `notes`.
 */

