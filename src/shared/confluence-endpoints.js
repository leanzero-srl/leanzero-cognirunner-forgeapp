export const CONFLUENCE_ENDPOINT_CATEGORIES = [...new Set(CONFLUENCE_ENDPOINTS.map((e) => e.category))];

/**
 * Compact Confluence endpoint catalog block for AI prompts.
 * Same contract as buildEndpointPromptBlock in jira-endpoints.js: lines grouped
 * by category as "METHOD path — description (notes)", optional fenced body
 * templates, hard-trimmed at maxBytes with a truncation marker.
 */
export const buildConfluenceEndpointPromptBlock = ({ categories, maxBytes = 4096, includeBodies = false } = {}) => {
  const wanted = categories ? new Set(categories) : null;
  const parts = [];
  for (const cat of CONFLUENCE_ENDPOINT_CATEGORIES) {
    if (wanted && !wanted.has(cat)) continue;
    const entries = CONFLUENCE_ENDPOINTS.filter((e) => e.category === cat);
    if (!entries.length) continue;
    const lines = entries.map((e) => {
      let line = `- ${e.method} ${e.path}${e.params ? e.params : ""} — ${e.description}${e.notes ? ` (${e.notes})` : ""}`;
      if (includeBodies && e.body) {
        line += `\n  Body template:\n\`\`\`json\n${e.body}\n\`\`\``;
      }
      return line;
    });
    parts.push(`${cat.toUpperCase()}:\n${lines.join("\n")}`);
  }
  let block = parts.join("\n\n");
  if (block.length > maxBytes) {
    block = `${block.slice(0, maxBytes)}\n…[endpoint list truncated]`;
  }
  return block;
};

export default CONFLUENCE_ENDPOINTS;
