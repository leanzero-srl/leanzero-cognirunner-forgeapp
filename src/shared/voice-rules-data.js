/**
 * AI DISCLAIMERS. The one class that is never acceptable anywhere in the text, in any
 * register, at any length: it tells the reader the answer came from a model, which is
 * the app's decision to disclose in the UI, not the agent's to blurt mid-sentence.
 */
export const AI_DISCLAIMERS = Object.freeze([
  "as an ai",
  "as a language model",
  "as an assistant",
  "i'm just an ai",
  "i am just an ai",
  "i'm an ai",
  "i am an ai",
  "i am a bot",
  "i'm a bot",
  "automated response",
  "this is an automated message",
  "generated by ai",
  "ai-generated",
]);

/**
 * Total words a message may spend, per register. These are not style advice: a reply
 * that is four times longer than the register promises is a different product, and the
 * whole point of the register is that the reader can predict the shape of what arrives.
 *
 * terse: the answer and nothing else. plain: the answer plus what it depends on.
 * warm: the answer, its context and one sentence of acknowledgement.
 */
export const REGISTER_WORD_CAPS = Object.freeze({ terse: 45, plain: 80, warm: 120 });

/** The register used when a record does not name one (the middle, never the widest). */
export const DEFAULT_REGISTER = "plain";

/**
 * Structural numbers. `maxSentenceWords` is a readability ceiling — past 45 words a
 * sentence in a ticket is a paragraph with no full stops. The burstiness pair encodes
 * the one measurable difference between human and generated prose in short messages:
 * people mix a long sentence with a short one, generators emit three medium ones.
 */
export const MAX_SENTENCE_WORDS = 45;
export const BURSTINESS_SHORT_WORDS = 8;
export const BURSTINESS_MIN_SENTENCES = 3;

/** Soft-warning thresholds. These are recorded, never blocking. */
export const WARN_EXCLAMATIONS = 1;
export const WARN_QUESTIONS = 2;

/** The whole table set, in the shape `lintVoice`'s third argument expects. */
export const VOICE_RULES_TABLES = Object.freeze({
  bannedOpeners: BANNED_OPENERS,
  methodLeaks: METHOD_LEAKS,
  signOffs: SIGN_OFFS,
  aiDisclaimers: AI_DISCLAIMERS,
  registerWordCaps: REGISTER_WORD_CAPS,
  defaultRegister: DEFAULT_REGISTER,
  maxSentenceWords: MAX_SENTENCE_WORDS,
  burstinessShortWords: BURSTINESS_SHORT_WORDS,
  burstinessMinSentences: BURSTINESS_MIN_SENTENCES,
  warnExclamations: WARN_EXCLAMATIONS,
  warnQuestions: WARN_QUESTIONS,
});
